/*
 *  函数名称：pid
 *  功能说明：PID 结构体模块源文件（仅保留结构体定义对应的头文件引用）
 *  参数说明：无
 *  函数返回：无
 *  备注信息：本文件不提供任何 PID 计算逻辑
 */

#include "pid.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     PID 参数初始化
// 参数说明     pid             PID 结构体指针
// 参数说明     kp              比例系数
// 参数说明     ki              积分系数
// 参数说明     kd              微分系数
// 返回参数     void
// 使用示例     pid_init(&pid, 10.0f, 0.0f, 0.0f);
// 备注信息     外部调用
//-------------------------------------------------------------------------------------------------------------------


void pid_init(PID* pid, float kp, float ki, float kd)
{
    pid->kp = kp;
    pid->ki = ki;
    pid->kd = kd;
    pid->integ = 0.0f;
    pid->error = 0.0f;
    pid->last_error = 0.0f;
}


